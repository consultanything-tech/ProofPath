const quantity = document.querySelector("#quantity");
const revision = new URLSearchParams(window.location.search).get("revision");
const mode = revision === "seeded-bug" || revision === "fixed" ? revision : "baseline";
const checkout = document.querySelector("#checkout-panel");
const active = document.querySelector("#checkout-active");
const email = document.querySelector("#email");
const postalCode = document.querySelector("#postal-code");
const emailError = document.querySelector("#email-error");
const postalCodeError = document.querySelector("#postal-code-error");
document.querySelector("#fixture-revision").textContent = mode;
const render = () => { const value = Math.max(0, Number.parseInt(quantity.value, 10) || 0); const cents = mode === "seeded-bug" && value === 2 ? 3900 : value * 3900; document.querySelector("#cart-quantity").textContent = String(value); document.querySelector("#cart-total-minor").textContent = String(cents); document.querySelector("#cart-total").textContent = `S$${(cents / 100).toFixed(2)}`; };
document.querySelector("#add").addEventListener("click", () => { quantity.value = "1"; render(); });
quantity.addEventListener("input", render);
document.querySelector("#checkout").addEventListener("click", () => {
  checkout.hidden = false;
  active.hidden = false;
  email.value = "";
  postalCode.value = "";
  emailError.hidden = true;
  postalCodeError.hidden = true;
  email.setAttribute("aria-invalid", "false");
  postalCode.setAttribute("aria-invalid", "false");
  document.querySelector("#checkout-confirmation")?.remove();
});
document.querySelector("#continue-checkout").addEventListener("click", () => {
  const blankEmail = !email.value.trim();
  const blankPostalCode = !postalCode.value.trim();
  emailError.hidden = !blankEmail;
  postalCodeError.hidden = !blankPostalCode;
  email.setAttribute("aria-invalid", String(blankEmail));
  postalCode.setAttribute("aria-invalid", String(blankPostalCode));
  if (blankEmail || blankPostalCode) return;
  checkout.hidden = true;
  active.hidden = true;
  document.querySelector("#checkout-confirmation")?.remove();
  const confirmation = document.createElement("p");
  confirmation.id = "checkout-confirmation";
  confirmation.textContent = "Synthetic checkout confirmed.";
  checkout.after(confirmation);
});
